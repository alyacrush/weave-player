const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
let click, message, headers;
const root='moz-extension://test/';
const chrome={browserAction:{onClicked:{addListener:f=>click=f}},tabs:{create:(o,f)=>f({id:9}),onRemoved:{addListener:()=>{}}},runtime:{getURL:p=>root+p,onMessage:{addListener:f=>message=f}},webRequest:{onHeadersReceived:{addListener:(f,filter,options)=>{headers=f;assert.deepEqual(Array.from(options),['responseHeaders']);}}}};
vm.runInNewContext(fs.readFileSync(__dirname+'/background.js','utf8'),{chrome,URL,Set,Map});
click();
const original=[{name:'Content-Security-Policy',value:"frame-ancestors 'self'"},{name:'Set-Cookie',value:'secret'}];
assert.equal(headers({tabId:9,url:'https://www.twitch.tv/popout/twitchdev/chat?secret=never-log',statusCode:200,responseHeaders:original}),undefined);
let result;
message({type:'read',tabId:9},{url:root+'probe.html'},r=>result=r);
assert.equal(result.length,1);assert.equal(result[0].headers.length,1);
assert.equal(result[0].headers[0].value,"frame-ancestors 'self'");
assert.ok(!JSON.stringify(result).includes('secret'));
message({type:'read',tabId:9},{url:'https://www.twitch.tv/',tab:{id:9},frameId:0},()=>assert.fail('untrusted read'));
message({type:'clear',tabId:9},{url:root+'probe.html'},()=>{});
message({type:'read',tabId:9},{url:root+'probe.html'},r=>assert.equal(r.length,0));
const manifest=JSON.parse(fs.readFileSync(__dirname+'/manifest.json','utf8'));
assert.ok(!manifest.permissions.includes('webRequestBlocking'));
console.log('PASS: read-only headers, scoped records, no cookie/query logging, extension-page messaging');
